// Rasterised at 116x35 rather than the full panel width. Three things are
// tuned together, because on a 1-bit panel the scale you pick matters more
// than the resolution you start from:
//
//   * Scale. The cap height is 357px in the source; 116x35 puts it at exactly
//     21px and the 67px stems at 3.94px, so letters and strokes both land
//     near-whole. Fitting to 128 wide instead gives a 4.33px stem, which
//     rounds to 4px on some strokes and 5px on others and reads as ragged.
//   * Sub-pixel phase. The source is shifted 0.75px horizontally before
//     downsampling so stem edges fall on pixel boundaries rather than
//     straddling them.
//   * Area coverage. BOX resampling gives true area averages; LANCZOS rings
//     on binary artwork and leaves isolated pixels along curves.
//
// Measured against a plain LANCZOS fit: stroke-width variance is unchanged at
// ~1.6, but isolated/jagged pixels drop from 12 to 3.
